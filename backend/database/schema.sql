-- Inventory Management System: full database creation script (PostgreSQL / Supabase).
-- Run on an empty database.
--
-- Always creates a default admin account:
--   username: admin
--   password: ChangeMe!2026   (must_change_password = true, change it on first login)

BEGIN;

-- ---------------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------------
CREATE TABLE public.users (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             varchar(50)  NOT NULL UNIQUE,
    full_name            varchar(120) NOT NULL,
    password_hash        varchar(255) NOT NULL,
    role                 varchar(20)  NOT NULL DEFAULT 'user',
    is_active            boolean      NOT NULL DEFAULT true,
    must_change_password boolean      NOT NULL DEFAULT false,
    created_at           timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_role CHECK (role IN ('admin', 'supervisor', 'user'))
);

COMMENT ON COLUMN public.users.role IS
    'admin: full system access incl. user management; '
    'supervisor: stocktake, reports, master data; '
    'user: data entry (IN / OUT / TRANSFER) and viewing';

-- ---------------------------------------------------------------------------
-- Locations -> zones -> bins
-- ---------------------------------------------------------------------------
CREATE TABLE public.locations (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code        varchar(20)  NOT NULL UNIQUE,
    name        varchar(120) NOT NULL,
    description text,
    address     text,
    is_active   boolean      NOT NULL DEFAULT true
);

CREATE TABLE public.zones (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    location_id bigint       NOT NULL REFERENCES public.locations (id),
    code        varchar(20)  NOT NULL,
    name        varchar(120) NOT NULL,
    description text,   -- purpose of the zone, e.g. inbound / outbound / holding
    created_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_zone_location_code UNIQUE (location_id, code)
);

CREATE TABLE public.bins (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    zone_id     bigint      NOT NULL REFERENCES public.zones (id),
    code        varchar(20) NOT NULL,
    description text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_bin_zone_code UNIQUE (zone_id, code)
);

-- ---------------------------------------------------------------------------
-- Products
-- ---------------------------------------------------------------------------
CREATE TABLE public.products (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,   -- internal key only
    barcode       varchar(64)  NOT NULL UNIQUE,                      -- the product identifier
    name          varchar(200) NOT NULL,
    category      varchar(80)  NOT NULL DEFAULT '',
    unit          varchar(20)  NOT NULL,
    reorder_level integer      NOT NULL DEFAULT 0,
    restock_at    timestamptz,                                       -- last restock date
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_product_reorder_nonneg CHECK (reorder_level >= 0)
);

-- ---------------------------------------------------------------------------
-- Stock
-- ---------------------------------------------------------------------------
CREATE TABLE public.stock_levels (
    product_id  bigint  NOT NULL REFERENCES public.products (id),
    location_id bigint  NOT NULL REFERENCES public.locations (id),
    bin_id      bigint  REFERENCES public.bins (id),   -- where the product sits in the location
    quantity    integer NOT NULL DEFAULT 0,
    PRIMARY KEY (product_id, location_id),
    CONSTRAINT ck_stock_qty_nonneg CHECK (quantity >= 0)
);
CREATE INDEX ix_stock_levels_bin ON public.stock_levels (bin_id);

-- Out of stock = total quantity across all locations is 0
CREATE VIEW public.product_stock WITH (security_invoker = true) AS
SELECT p.id,
       p.barcode,
       p.name,
       p.category,
       p.unit,
       p.reorder_level,
       p.restock_at,
       COALESCE(sum(s.quantity), 0)::integer AS total_quantity,
       COALESCE(sum(s.quantity), 0) = 0      AS out_of_stock
  FROM public.products p
  LEFT JOIN public.stock_levels s ON s.product_id = p.id
 GROUP BY p.id;

-- ---------------------------------------------------------------------------
-- Stocktakes
-- ---------------------------------------------------------------------------
CREATE TABLE public.stocktakes (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    location_id bigint      NOT NULL REFERENCES public.locations (id),
    status      varchar(10) NOT NULL DEFAULT 'draft',
    note        text,
    created_by  bigint      NOT NULL REFERENCES public.users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    posted_by   bigint      REFERENCES public.users (id),
    posted_at   timestamptz,
    CONSTRAINT ck_stocktake_status CHECK (status IN ('draft', 'posted'))
);
CREATE UNIQUE INDEX uq_stocktake_one_draft_per_location
    ON public.stocktakes (location_id) WHERE status = 'draft';

CREATE TABLE public.stocktake_lines (
    stocktake_id bigint  NOT NULL REFERENCES public.stocktakes (id) ON DELETE CASCADE,
    product_id   bigint  NOT NULL REFERENCES public.products (id),
    counted_qty  integer,
    system_qty   integer,
    PRIMARY KEY (stocktake_id, product_id),
    CONSTRAINT ck_line_counted_nonneg CHECK (counted_qty IS NULL OR counted_qty >= 0)
);

-- ---------------------------------------------------------------------------
-- Transactions (audit trail of every stock movement)
-- ---------------------------------------------------------------------------
CREATE TABLE public.transactions (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    type             varchar(12)  NOT NULL,
    product_id       bigint       NOT NULL REFERENCES public.products (id),
    from_location_id bigint       REFERENCES public.locations (id),
    to_location_id   bigint       REFERENCES public.locations (id),
    quantity         integer      NOT NULL,
    reference        varchar(100),
    note             text,
    submission_id    uuid         NOT NULL,
    stocktake_id     bigint       REFERENCES public.stocktakes (id),
    user_id          bigint       NOT NULL REFERENCES public.users (id),
    created_at       timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_txn_type CHECK (type IN ('IN', 'OUT', 'TRANSFER', 'ADJUSTMENT')),
    CONSTRAINT ck_txn_qty_pos CHECK (quantity > 0),
    CONSTRAINT ck_txn_locations CHECK (
           (type = 'IN'         AND from_location_id IS NULL     AND to_location_id IS NOT NULL)
        OR (type = 'OUT'        AND from_location_id IS NOT NULL AND to_location_id IS NULL)
        OR (type = 'TRANSFER'   AND from_location_id IS NOT NULL AND to_location_id IS NOT NULL
                                AND from_location_id <> to_location_id)
        OR (type = 'ADJUSTMENT' AND (from_location_id IS NULL) <> (to_location_id IS NULL))
    )
);
CREATE INDEX ix_txn_created_at      ON public.transactions (created_at);
CREATE INDEX ix_txn_product_created ON public.transactions (product_id, created_at);
CREATE INDEX ix_txn_type_created    ON public.transactions (type, created_at);
CREATE INDEX ix_txn_from_location   ON public.transactions (from_location_id);
CREATE INDEX ix_txn_to_location     ON public.transactions (to_location_id);

-- ---------------------------------------------------------------------------
-- Row level security: on for every table. The Flask backend connects as the
-- database owner, so no policies are needed; this blocks the public Supabase API.
-- ---------------------------------------------------------------------------
